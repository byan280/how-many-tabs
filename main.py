# How Many Tabs Do You Have Open
#
# This program writes one fixed line to standard output.
# It takes no input, reads no files, and uses no randomness,
# so every run produces exactly the same single line.
#
# The line lives in the print statement below and nowhere else.
# Nothing is printed before it and nothing after it.
# The process ends normally right after the line appears.
# The joke is not the number of tabs. It is the grief
# for the one tab that got away.
# Run it with: python3 main.py
# One fixed line on stdout.
print("I closed a tab once. I still think about it.")
